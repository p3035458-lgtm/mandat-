// Генератор C++-таблиць даних з оригінального game.js.
// Беремо літерали ISSUES / REG / RIVALS / BIOS прямо з вихідника й видаємо
// src/core/DataTables.gen.cpp — так у даних не може бути ручних помилок.
//
//   node tools/gen_data.mjs <mandate-react/src/game.js> > src/core/DataTables.gen.cpp
import fs from 'node:fs';

const src = fs.readFileSync(process.argv[2], 'utf8');
const a = src.indexOf('const ISSUES=');
const b = src.indexOf('const STAFF=');
if (a < 0 || b < 0) throw new Error('markers not found');
// відрізаємо рядки, що не є даними (REGI, COUNTRY — повернемо руками)
const block = src.slice(a, b)
  .replace(/const REGI=[^\n]*\n/, '')
  .replace(/const COUNTRY=[^\n]*\n/, '');
const D = new Function(block + '\nreturn {ISSUES,ISS,REG,RIVALS,BIOS};')();

// Досягнення: беремо лише id/назву/опис (умови — це функції, портуються вручну у Фазі 3)
const achLine = src.split('\n').find(l => l.startsWith('const ACH='));
const ACH = achLine ? new Function(achLine + '\nreturn ACH;')() : [];

const q = s => JSON.stringify(String(s));          // C++ рядок (UTF-8)
const num = v => (Number.isInteger(v) ? v + '.0' : String(v));
const ISS = D.ISS;
const CAND = ['player', 'carter', 'miller', 'wilson'];

const arr = (obj, keys) => '{' + keys.map(k => num(obj[k] ?? 0)).join(', ') + '}';

let o = '';
o += '// AUTO-GENERATED by tools/gen_data.mjs from game.js — НЕ РЕДАГУВАТИ ВРУЧНУ.\n';
o += '#include "Data.hpp"\n\nnamespace mandat::core {\n\n';

o += 'const std::array<IssueInfo, NISS>& issueInfo() {\n  static const std::array<IssueInfo, NISS> v = {{\n';
for (const k of ISS) o += `    {${q(k)}, ${q(D.ISSUES[k])}},\n`;
o += '  }};\n  return v;\n}\n\n';

o += 'const std::vector<Region>& regions() {\n  static const std::vector<Region> v = {\n';
for (const R of D.REG) {
  o += '    {' + [
    q(R.id), q(R.name), num(R.pop), R.ev, R.turn, R.undec, num(R.youth), R.report,
    num(R.gdpc), num(R.un), q(R.desc),
    '{' + R.box.join(', ') + '}',
    '{' + R.hot.map(p => `{${p[0]}, ${p[1]}}`).join(', ') + '}',
    arr(R.sal, ISS), arr(R.lean, CAND),
  ].join(', ') + '},\n';
}
o += '  };\n  return v;\n}\n\n';

o += 'const std::vector<Rival>& rivals() {\n  static const std::vector<Rival> v = {\n';
for (const k of Object.keys(D.RIVALS)) {
  const r = D.RIVALS[k];
  o += '    {' + [q(k), q(r.name), q(r.party), q(r.color), num(r.trust), num(r.rec), r.power, q(r.deal),
    arr(r.issues, ISS), q(r.blurb)].join(', ') + '},\n';
}
o += '  };\n  return v;\n}\n\n';

o += 'const std::vector<Bio>& bios() {\n  static const std::vector<Bio> v = {\n';
for (const bio of D.BIOS) {
  const iss = Object.entries(bio.issues || {}).map(([k, x]) => `{${ISS.indexOf(k)}, ${num(x)}}`).join(', ');
  const bon = Object.entries(bio.bonus || {}).map(([k, x]) => `{${q(k)}, ${num(x)}}`).join(', ');
  o += '    {' + [q(bio.id), q(bio.name), q(bio.desc), num(bio.cha), num(bio.comp), num(bio.budget),
    num(bio.trust), num(bio.rec), '{' + iss + '}', '{' + bon + '}', num(bio.skeleton), q(bio.skel)].join(', ') + '},\n';
}
o += '  };\n  return v;\n}\n\n';

o += 'const std::vector<AchievementDef>& achievementDefs() {\n  static const std::vector<AchievementDef> v = {\n';
for (const a of ACH) o += `    {${q(a[0])}, ${q(a[1])}, ${q(a[2])}},\n`;
o += '  };\n  return v;\n}\n\n} // namespace mandat::core\n';
process.stdout.write(o);
